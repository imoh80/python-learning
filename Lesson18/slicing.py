"""
Slicing

Question:
Create a list of coffee drinks.
Print different portions of the list using slicing.
"""

drinks = [
    "Latte",
    "Mocha",
    "Espresso",
    "Cappuccino",
    "Americano"
]

print("First two drinks:", drinks[:2])
print("Middle drinks:", drinks[1:4])
print("Last two drinks:", drinks[-2:])